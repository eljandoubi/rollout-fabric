"""A softmax policy over a fixed menu of candidate programs per task, trained with REINFORCE."""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

import numpy as np
import numpy.typing as npt

Logits = npt.NDArray[np.float64]


@dataclass(frozen=True)
class Sample:
    """One completion and what the learner needs from it."""

    sample_id: int
    task: int
    choice: int
    reward: float
    behavior_logp: float
    version: int  # version of the policy that generated it


def softmax(logits: Logits) -> Logits:
    z = logits - logits.max(axis=-1, keepdims=True)
    e = np.exp(z)
    return np.asarray(e / e.sum(axis=-1, keepdims=True))


def sample_choice(logits: Logits, task: int, rng: np.random.Generator) -> tuple[int, float]:
    """Draw a candidate for `task`; returns it with its log-probability under `logits`."""
    p = softmax(logits[task])
    choice = int(rng.choice(len(p), p=p))
    return choice, float(np.log(p[choice]))


class Policy:
    """Logits table of shape (tasks, choices). `version` counts the updates applied."""

    def __init__(self, n_tasks: int, n_choices: int, lr: float = 0.5, clip: float = 2.0) -> None:
        self.logits: Logits = np.zeros((n_tasks, n_choices))
        self.lr = lr
        self.clip = clip
        self.version = 0

    def probs(self, task: int) -> Logits:
        return softmax(self.logits[task])

    def update(self, batch: Sequence[Sample]) -> float:
        """One REINFORCE step with the batch mean as baseline.

        A sample generated by an older version is corrected by the importance ratio
        pi_now / pi_behavior, clipped at `clip`. Returns the mean ratio used.
        """
        if not batch:
            raise ValueError("empty batch")
        baseline = float(np.mean([s.reward for s in batch]))
        grad = np.zeros_like(self.logits)
        ratios = []
        for s in batch:
            p = softmax(self.logits[s.task])
            ratio = min(float(np.exp(np.log(p[s.choice]) - s.behavior_logp)), self.clip)
            ratios.append(ratio)
            onehot = np.zeros_like(p)
            onehot[s.choice] = 1.0
            grad[s.task] += (s.reward - baseline) * ratio * (onehot - p)
        self.logits += self.lr * grad / len(batch)
        self.version += 1
        return float(np.mean(ratios))
